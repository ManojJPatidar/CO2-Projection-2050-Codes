"""### Imports and settings"""

import sys, pickle, time, warnings
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))
warnings.filterwarnings("ignore")

import numpy as np
from statsmodels.tsa.statespace.sarimax import SARIMAX

from ghglib.data import ROOT
from ghglib.features import H

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
ORD = pickle.load(open(RES / "pred_baselines.pkl", "rb"))["orders"]

"""### SARIMA forecasts at every origin"""

out = {}
t0 = time.time()
for k, r in C.items():
    y = r["y"]; p, d, q, P, D, Q = ORD[k]
    m_tr = SARIMAX(y[:r["i_tr"] + 1], order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300)
    m_tv = SARIMAX(y[:r["i_va"] + 1], order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300)
    fc = np.full((len(r["origins"]), H), np.nan)
    for i, t in enumerate(r["origins"]):
        mod = m_tr if t < r["i_va"] else m_tv
        fc[i] = mod.apply(y[:t + 1]).forecast(H)
    out[k] = dict(fc=fc, params_tr=m_tr.params, params_tv=m_tv.params)
    print(k, f"{time.time() - t0:.0f}s", flush=True)

"""### Save"""

with open(RES / "sarima_paths.pkl", "wb") as f:
    pickle.dump(out, f)
print("done")