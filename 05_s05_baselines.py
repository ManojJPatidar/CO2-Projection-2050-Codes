"""### Imports and settings"""

import sys, pickle, time, warnings, logging, itertools
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))
warnings.filterwarnings("ignore")
logging.getLogger("cmdstanpy").setLevel(logging.ERROR)

import numpy as np
import pandas as pd
from statsmodels.tsa.statespace.sarimax import SARIMAX
from prophet import Prophet
import xgboost as xgb

from ghglib.data import ROOT
from ghglib.features import H, L

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
KEYS = list(C.keys())


def test_origins(r):
    return np.arange(r["i_va"], r["n"] - H)


def split_pos(r, part):
    o = r["origins"]
    if part == "train":
        m = o + H <= r["i_tr"]
    elif part == "val":
        m = (o >= r["i_tr"]) & (o + H <= r["i_va"])
    else:
        m = (o >= r["i_va"]) & (o + H <= r["n"] - 1)
    return np.where(m)[0]


out = {m: {} for m in ["SNaive-drift", "STL-naive", "SARIMA", "Prophet", "XGBoost-STL", "XGBoost-raw",
                       "SPL-prophet-causal", "SPL-prophet-leaky"]}
orders = {}
t0 = time.time()

"""### Simple references"""

for k in KEYS:
    r = C[k]; y = r["y"]; T = test_origins(r)
    out["SNaive-drift"][k] = np.array([[y[t + h - 12] + (y[t] - y[t - 12]) for h in range(1, H + 1)] for t in T])
    out["STL-naive"][k] = r["Bc"][split_pos(r, "test")]

"""### SARIMA: order by AIC on the training period, parameters on train+val, rolling state over test"""

for k in KEYS:
    r = C[k]; y = r["y"]; T = test_origins(r)
    ytr = y[:r["i_tr"] + 1]
    best = (np.inf, None)
    for p, q, P in itertools.product([0, 1, 2], [0, 1, 2], [0, 1]):
        try:
            res = SARIMAX(ytr, order=(p, 1, q), seasonal_order=(P, 1, 1, 12)).fit(disp=False, maxiter=200)
            if res.aic < best[0]:
                best = (res.aic, (p, 1, q, P, 1, 1))
        except Exception:
            pass
    p, d, q, P, D, Q = best[1]; orders[k] = best[1]
    res = SARIMAX(y[:r["i_va"] + 1], order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300)
    out["SARIMA"][k] = np.array([res.apply(y[:t + 1]).forecast(H) for t in T])
    print("SARIMA", k, best[1], f"{time.time() - t0:.0f}s", flush=True)

"""### Prophet (refit at every origin) and the Prophet part of SPL"""

def prophet_fc(dates, values, seasonal=True):
    m = Prophet(yearly_seasonality=seasonal, weekly_seasonality=False, daily_seasonality=False)
    m.fit(pd.DataFrame({"ds": dates, "y": values}))
    fut = pd.date_range(dates[-1], periods=H + 1, freq="MS")[1:]
    return m.predict(pd.DataFrame({"ds": fut}))["yhat"].values


for k in KEYS:
    r = C[k]; y = r["y"]; dates = r["dates"]; T = test_origins(r)
    dl_full = r["leaky_comps"][0]
    pf, sc_, sl_ = [], [], []
    for t in T:
        pf.append(prophet_fc(dates[:t + 1], y[:t + 1]))
        d_c, _ = r["test_comps"][t]
        sc_.append(prophet_fc(dates[:t + 1], d_c[:t + 1], seasonal=False))
        sl_.append(prophet_fc(dates[:t + 1], dl_full[:t + 1], seasonal=False))
    out["Prophet"][k] = np.array(pf)
    out["SPL-prophet-causal"][k] = np.array(sc_)
    out["SPL-prophet-leaky"][k] = np.array(sl_)
    print("Prophet", k, f"{time.time() - t0:.0f}s", flush=True)

"""### XGBoost on causal-STL features (pooled, multi-output)"""

def pooled(X, Y, part):
    xs, ys = [], []
    for k in KEYS:
        r = C[k]; p = split_pos(r, part)
        xs.append(r[X][p].reshape(len(p), -1)); ys.append(r[Y][p])
    return np.concatenate(xs), np.concatenate(ys)


def fit_xgb(Xtr, Ytr, Xva, Yva):
    kw = dict(n_estimators=2000, max_depth=4, learning_rate=0.03, subsample=0.8, colsample_bytree=0.8,
              tree_method="hist", random_state=7)
    m = xgb.XGBRegressor(early_stopping_rounds=50, **kw)
    m.fit(Xtr, Ytr, eval_set=[(Xva, Yva)], verbose=False)
    nb = m.best_iteration + 1
    kw["n_estimators"] = nb
    m2 = xgb.XGBRegressor(**kw)
    m2.fit(np.concatenate([Xtr, Xva]), np.concatenate([Ytr, Yva]), verbose=False)
    return m2, nb


Xtr, Ytr = pooled("Xc", "Zc", "train"); Xva, Yva = pooled("Xc", "Zc", "val")
mx, nb = fit_xgb(Xtr, Ytr, Xva, Yva)
for k in KEYS:
    r = C[k]; p = split_pos(r, "test")
    out["XGBoost-STL"][k] = r["Bc"][p] + mx.predict(r["Xc"][p].reshape(len(p), -1)) * r["sc"]["z"]
print("XGBoost-STL trees", nb, flush=True)

"""### XGBoost on raw lags + date features (Rezaei et al. style)"""

def raw_feats(k, part):
    r = C[k]; p = split_pos(r, part); y = r["y"]; o = r["origins"][p]; dates = r["dates"]
    onehot = np.zeros((len(p), len(KEYS))); onehot[:, KEYS.index(k)] = 1
    lags = np.array([y[t - 11:t + 1] for t in o])
    mon = dates[o].month.values
    yr = dates[o].year.values + (mon - 1) / 12
    X = np.column_stack([lags, np.sin(2 * np.pi * mon / 12), np.cos(2 * np.pi * mon / 12), yr, onehot])
    Y = np.array([y[t + 1:t + 1 + H] for t in o])
    return X, Y


def pooled_raw(part):
    a = [raw_feats(k, part) for k in KEYS]
    return np.concatenate([x for x, _ in a]), np.concatenate([y for _, y in a])


Xtr, Ytr = pooled_raw("train"); Xva, Yva = pooled_raw("val")
mr, nb2 = fit_xgb(Xtr, Ytr, Xva, Yva)
for k in KEYS:
    X, _ = raw_feats(k, "test")
    out["XGBoost-raw"][k] = mr.predict(X)
print("XGBoost-raw trees", nb2, flush=True)

with open(RES / "pred_baselines.pkl", "wb") as f:
    pickle.dump(dict(pred=out, orders=orders, keys=KEYS), f)
pd.Series({f"{k[0]}-{k[1]}": v for k, v in orders.items()}).to_csv(RES / "sarima_orders.csv")
print("done", f"{time.time() - t0:.0f}s")