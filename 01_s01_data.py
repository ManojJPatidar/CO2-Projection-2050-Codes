import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates

from ghglib.data import (load_panel, load_gistemp, load_oni, load_sf6_global, split_dates,
                         GASES, SITES, UNITS, LABEL, SITE_NAME, SITE_LAT, ROOT)
from ghglib.impute import causal_fill
from ghglib.plotting import save, FULL, SITE_COL, SITE_MK

RES = ROOT / "results"; RES.mkdir(exist_ok=True)
sp = split_dates()

"""### Panel: raw (with gaps) and analysis-ready (real gaps filled causally with data <= train end)"""

P = load_panel()
raw, filled = {}, {}
for (g, s), y in P.items():
    raw[(g, s)] = y
    if y.isna().any():
        hist = y[y.index <= sp["train_end"]]
        f = causal_fill(hist)
        z = y.copy(); z[f.index] = f.values
        filled[(g, s)] = z
    else:
        filled[(g, s)] = y

long = pd.concat([pd.DataFrame({"gas": g, "site": s, "date": y.index, "value_raw": raw[(g, s)].values,
                                "value": filled[(g, s)].values}) for (g, s), y in P.items()])
long.to_csv(RES / "panel_monthly.csv", index=False)

from google.colab import drive
drive.mount('/content/drive')

"""### Summary table"""

rows = []
for (g, s), y in raw.items():
    tr = y[y.index <= sp["train_end"]]
    yf = filled[(g, s)]
    yr = yf.groupby(yf.index.year).agg(['mean', 'size'])
    yr = yr[yr['size'] == 12]['mean']          # complete calendar years only
    gr = np.diff(yr.values)
    rows.append(dict(gas=g, site=s, start=y.index[0].strftime("%Y-%m"), end=y.index[-1].strftime("%Y-%m"),
                     months=len(y), missing=int(y.isna().sum()), mean=y.mean(), first_year=yr.iloc[0],
                     last_year=yr.iloc[-1], growth_mean=gr.mean(), growth_last10=gr[-10:].mean(),
                     train_months=int((y.index <= sp["train_end"]).sum()),
                     val_months=int(((y.index > sp["train_end"]) & (y.index <= sp["val_end"])).sum()),
                     test_months=int((y.index > sp["val_end"]).sum())))
summary = pd.DataFrame(rows)
summary.to_csv(RES / "data_summary.csv", index=False)
print(summary.round(2).to_string())

