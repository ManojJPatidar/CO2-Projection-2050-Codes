"""### Figure: data overview"""

fig, axs = plt.subplots(1, 3, figsize=(FULL, 2.7))
for ax, g in zip(axs, GASES):
    for s in SITES:
        y = raw[(g, s)]
        ax.plot(y.index, y.values, color=SITE_COL[s], marker=SITE_MK[s], markevery=48,
                lw=0.8 if s != "GLB" else 1.5, ms=3.5, label=s)
        gaps = y.isna()
        if gaps.any():
            ax.plot(y.index[gaps], filled[(g, s)][gaps], "x", color="k", ms=4, mew=1.5)
    for d in (sp["train_end"], sp["val_end"]):
        ax.axvline(d, color="k", ls="--", lw=0.9)
    ax.set_ylabel(f"{LABEL[g]} ({UNITS[g]})")
    ax.set_title(f"({'abc'[GASES.index(g)]}) {LABEL[g]}", loc="center")
    ax.xaxis.set_major_locator(mdates.YearLocator(20 if g != "n2o" else 10)); ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
h_, l_ = axs[0].get_legend_handles_labels()
fig.tight_layout(rect=(0, 0.1, 1, 1))
fig.legend(h_, l_, loc="lower center", ncol=5, fontsize=7.5, frameon=False)
plt.show()
save(fig, "fig01_data_overview")