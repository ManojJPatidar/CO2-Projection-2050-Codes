"""### Imports and settings"""

import sys, pickle, time, logging, warnings
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))
warnings.filterwarnings("ignore"); logging.getLogger("cmdstanpy").setLevel(logging.ERROR)

import numpy as np
import pandas as pd

from ghglib.data import ROOT
from ghglib.features import H
from ghglib.impute import linear, locf, seasonal_trend, prophet_fill
from ghglib.pipeline import load_members, sarima_dl_forecasts

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
KEYS = list(C.keys())
nets = load_members(RES / "models", prefix="res_")
SP = pickle.load(open(RES / "sarima_paths.pkl", "rb"))
ORD = pickle.load(open(RES / "pred_baselines.pkl", "rb"))["orders"]
GAPS = [1, 3, 6]

"""### Edge-gap experiment"""

rows = []
t0 = time.time()
for k in KEYS:
    r = C[k]; y = r["y"]; dates = r["dates"]; months = dates.month.values
    full = pd.Series(y, index=dates)
    T_all = np.arange(r["i_va"], r["n"] - H)
    for T in T_all[::3]:
        truth = y[T + 1:T + 1 + H]
        ref = sarima_dl_forecasts(y[:T + 1], months, r["sc"], nets, ORD[k], SP[k]["params_tv"]).mean(0)
        rows.append(dict(gas=k[0], site=k[1], T=T, g=0, method="Complete history", leaky=False,
                         imp_rmse=0.0, **{f"e{h}": ref[h - 1] - truth[h - 1] for h in range(1, H + 1)}))
        for g in GAPS:
            gap = np.arange(T - g + 1, T + 1)
            rec_full = full.copy(); rec_full.iloc[gap] = np.nan          # whole record, gap masked
            hist = full.iloc[:T + 1].copy(); hist.iloc[gap] = np.nan      # history only
            fills = {
                ("Linear (full record)", True): linear(rec_full).iloc[:T + 1],
                ("Prophet (full record)", True): prophet_fill(rec_full).iloc[:T + 1],
                ("LOCF", False): locf(hist),
                ("STL-seasonal (causal)", False): seasonal_trend(hist),
                ("Prophet (history only)", False): prophet_fill(hist),
            }
            for (name, lk), f in fills.items():
                yh = f.values
                imp = np.sqrt(np.mean((yh[gap] - y[gap]) ** 2))
                fc = sarima_dl_forecasts(yh, months, r["sc"], nets, ORD[k], SP[k]["params_tv"]).mean(0)
                rows.append(dict(gas=k[0], site=k[1], T=T, g=g, method=name, leaky=lk, imp_rmse=imp,
                                 **{f"e{h}": fc[h - 1] - truth[h - 1] for h in range(1, H + 1)}))
    print(k, f"{time.time() - t0:.0f}s", flush=True)

"""### Summary and save"""

E = pd.DataFrame(rows)
E.to_csv(RES / "edge_gap_raw.csv", index=False)
ecols = [f"e{h}" for h in range(1, H + 1)]
E["fc_rmse_h1"] = E["e1"].abs()
summ = (E.assign(se=lambda d: (d[ecols] ** 2).mean(1), se1=lambda d: d["e1"] ** 2)
        .groupby(["gas", "g", "method", "leaky"])
        .agg(imp_rmse=("imp_rmse", "mean"), fc_rmse=("se", lambda v: np.sqrt(v.mean())),
             fc_rmse_h1=("se1", lambda v: np.sqrt(v.mean()))).reset_index())
summ.to_csv(RES / "edge_gap_summary.csv", index=False)
print(summ.round(3).to_string())