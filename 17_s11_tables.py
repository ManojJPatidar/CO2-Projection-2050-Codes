     r"Study & Data and setting & Method & Reported accuracy \\", r"\midrule",
     r"\citet{yildirim2026} & NOAA global mean, test 2015--2024 & SARIMA; LSTM & RMSE 0.451 / 0.497\,ppm; $R=0.994$ / 0.993$^{a}$ \\",
     r"\citet{liu2025} & 6 NOAA flask sites, monthly & STL-Prophet-LSTM (full-record STL) & Mean RMSE 0.67\,ppm, $R^2=0.99$ \\",
     r"\citet{rezaei2025} & Global CO$_2$ (IMF), 2000--2024 & Prophet; Bi-LSTM; XGBoost & RMSE 0.035$^{b}$; 1.30; 1.37 \\",
     r"\citet{park2025} & Seoul, hourly, urban & RF, LSTM, ensemble & $R=0.91$--0.96; RMSE 6.6--10.2\,ppm \\",
     r"\midrule",
     r"\multicolumn{4}{@{}l}{\textit{B. Re-implemented on our data (RMSE in ppm: $h=1$ / mean $h=1$--12)}} \\",
