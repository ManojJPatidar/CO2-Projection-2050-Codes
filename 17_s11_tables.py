     r"\caption{Benchmark comparison for CO$_2$. A: published results (not directly comparable: data, periods, horizons and units differ). B: published methods re-run on our data with the leakage-free rolling-origin protocol (test 2018--2025). RMSE is given at $h=1$ month and averaged over $h=1$--12; $R^2$ is for $h=1$--12. ``Stations'' is the mean over BRW, MLO, SMO and SPO.}\label{tab:bench}",
