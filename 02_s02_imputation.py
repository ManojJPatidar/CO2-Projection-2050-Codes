"""### Imports and settings"""

import sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))

import zlib

import numpy as np
import pandas as pd

from ghglib.data import ROOT, GASES, SITES
from ghglib.impute import METHODS, mask_mcar, mask_blocks

RES = ROOT / "results"
panel = pd.read_csv(RES / "panel_monthly.csv", parse_dates=["date"])
SCEN = [("MCAR 5%", "mcar", 0.05), ("MCAR 10%", "mcar", 0.10), ("MCAR 20%", "mcar", 0.20),
        ("Block 3 m", "block", 3), ("Block 6 m", "block", 6), ("Block 12 m", "block", 12)]
REPS = 10

"""### Reconstruction experiment"""

rows = []
for g in GASES:
    for s in SITES:
        d = panel[(panel.gas == g) & (panel.site == s)].set_index("date")
        truth = d["value"]
        observed = d["value_raw"].notna().values
        n = len(truth)
        for name, kind, par in SCEN:
            for rep in range(REPS):
                rng = np.random.default_rng(1000 * rep + zlib.crc32(f"{g}{s}{name}".encode()) % 997)
                m = mask_mcar(n, par, rng) if kind == "mcar" else mask_blocks(n, par, 0.10, rng)
                m &= observed                     # score only months that were really observed
                x = truth.copy(); x[m] = np.nan
                for meth, f in METHODS.items():
                    est = f(x)
                    err = est[m].values - truth[m].values
                    rows.append(dict(gas=g, site=s, scenario=name, rep=rep, method=meth,
                                     rmse=np.sqrt(np.mean(err ** 2)), mae=np.mean(np.abs(err)),
                                     mape=100 * np.mean(np.abs(err) / truth[m].values), n=int(m.sum())))
        print(g, s, "done", flush=True)

"""### Save results"""

res = pd.DataFrame(rows)
res.to_csv(RES / "imputation_reconstruction.csv", index=False)
tab = res.groupby(["gas", "scenario", "method"])["rmse"].mean().unstack("method")
print(tab.round(3).to_string())