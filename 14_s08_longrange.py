import numpy as np
import pandas as pd
import torch
from statsmodels.tsa.statespace.sarimax import SARIMAX
import statsmodels.api as sm
from prophet import Prophet

from ghglib.data import ROOT
from ghglib.features import SeriesFeatures, H
from ghglib.dl import train_member, predict
from ghglib.pipeline import load_members, sarima_dl_paths, sarima_model, window, ARCHS, SEEDS

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
ORD = pickle.load(open(RES / "pred_baselines.pkl", "rb"))["orders"]
KEYS = list(C.keys())
Z95, Z80 = 1.959964, 1.281552
CUT = {"co2": ("2001-12-01", "2005-12-01"), "ch4": ("2001-12-01", "2005-12-01"), "n2o": ("2006-12-01", "2010-12-01")}

"""### Helper functions"""

def month_index(dates, extra):
    return pd.date_range(dates[0], periods=len(dates) + extra, freq="MS")


def stat_baselines(y, dates, order, n_ahead):
    """SARIMA, Prophet and quadratic-trend forecasts with 80/95 % intervals."""
    out = {}
    p, d, q, P, D, Q = order
    res = SARIMAX(y, order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300)
    fc = res.get_forecast(n_ahead)
    mu = fc.predicted_mean; sd = np.sqrt(fc.var_pred_mean)
    out["SARIMA"] = (mu, sd)
    m = Prophet(yearly_seasonality=True, weekly_seasonality=False, daily_seasonality=False, interval_width=0.95)
    m.fit(pd.DataFrame({"ds": dates, "y": y}))
    fut = pd.date_range(dates[-1], periods=n_ahead + 1, freq="MS")[1:]
    pr = m.predict(pd.DataFrame({"ds": fut}))
    out["Prophet"] = (pr["yhat"].values, (pr["yhat_upper"] - pr["yhat_lower"]).values / (2 * Z95))
    tt = np.arange(len(y) + n_ahead) / 12.0
    mon = np.r_[dates.month.values, fut.month.values]
    Xq = np.column_stack([np.ones_like(tt), tt, tt ** 2] +
                         [f(2 * np.pi * k * mon / 12) for k in (1, 2) for f in (np.sin, np.cos)])
    ols = sm.OLS(y, Xq[:len(y)]).fit()
    pq = ols.get_prediction(Xq[len(y):]).summary_frame(alpha=0.05)
    out["Quadratic trend"] = (pq["mean"].values, (pq["obs_ci_upper"] - pq["obs_ci_lower"]).values / (2 * Z95))
    return out


def dl_band(paths, sd12, n):
    h = np.arange(1, n + 1)
    mu = paths.mean(0)
    sd = np.sqrt(paths.var(0) + (h / 12.0) * sd12 ** 2)
    return mu, sd

"""### Backtest"""

t0 = time.time()
bt_feat, Xs = {}, {"train": ([], []), "val": ([], [])}
for k in KEYS:
    r = C[k]; dates = r["dates"]; y = r["y"]
    tr_end, cut = pd.Timestamp(CUT[k[0]][0]), pd.Timestamp(CUT[k[0]][1])
    i_cut = int(np.where(dates == cut)[0][0]); i_tr = int(np.where(dates == tr_end)[0][0])
    y_hist = pd.Series(y[:i_cut + 1], index=dates[:i_cut + 1])
    F = SeriesFeatures(y_hist, tr_end)
    p, d, q, P, D, Q = ORD[k]
    par_tr = SARIMAX(y[:i_tr + 1], order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300).params
    par_cut = SARIMAX(y[:i_cut + 1], order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300).params
    bt_feat[k] = dict(F=F, i_cut=i_cut, i_tr=i_tr, par_tr=par_tr, par_cut=par_cut)
    for t in range(F.first_origin(), i_cut - H + 1):
        part = "train" if t + H <= i_tr else ("val" if t >= i_tr else None)
        if part is None:
            continue
        xc, _, _ = F.x_causal(t)
        s_fc = sarima_model(y[:t + 1], ORD[k], par_tr).forecast(H)
        Xs[part][0].append(xc); Xs[part][1].append((y[t + 1:t + 1 + H] - s_fc) / F.sc_z)
    print("bt features", k, f"{time.time() - t0:.0f}s", flush=True)
Xtr, Ytr = np.array(Xs["train"][0], np.float32), np.array(Xs["train"][1], np.float32)
Xva, Yva = np.array(Xs["val"][0], np.float32), np.array(Xs["val"][1], np.float32)
print("backtest samples", Xtr.shape, Xva.shape, flush=True)

"""### Train-or-load switch"""

TRAIN_MODELS = False   # False: load the trained weights saved in results/models; True: retrain from scratch (CPU)
import torch
from ghglib.dl import ARCH


def load_net(arch, fname, n_in, n_out=H):
    net = ARCH[arch](n_in, n_out)
    net.load_state_dict(torch.load(RES / "models" / fname, map_location="cpu"))
    net.eval()
    return net

"""### Train or load backtest networks"""

bt_nets = []
for a in ARCHS:
    for sd in SEEDS:
        if TRAIN_MODELS:
            net, ep, vl = train_member(a, Xtr, Ytr, Xva, Yva, sd)
            torch.save(net.state_dict(), RES / "models" / f"bt_{a}_{sd}.pt")
            print("bt net", a, sd, ep, round(vl, 3), f"{time.time() - t0:.0f}s", flush=True)
        else:
            net = load_net(a, f"bt_{a}_{sd}.pt", Xtr.shape[2])
        bt_nets.append(net)

"""### Backtest forecasts and scores"""

# validation 12-month errors of the backtest ensemble -> accumulated-error scale
bt_rows, bt_paths = [], {}
for k in KEYS:
    r = C[k]; b = bt_feat[k]; F = b["F"]; i_cut = b["i_cut"]
    y = r["y"]; dates = r["dates"]; n_ahead = r["n"] - 1 - i_cut
    sc = dict(d=F.sc_d, s=F.sc_s, r=F.sc_r, z=F.sc_z)
    e12 = []
    for t in range(b["i_tr"], i_cut - H + 1):
        xc, _, _ = F.x_causal(t)
        fc = sarima_model(y[:t + 1], ORD[k], b["par_tr"]).forecast(H) + \
            np.mean([predict(n, xc[None])[0] for n in bt_nets], 0) * F.sc_z
        e12.append(fc[-1] - y[t + H])
    sd12 = np.sqrt(np.mean(np.square(e12)))
    months_all = month_index(dates, 0).month.values
    paths = sarima_dl_paths(y[:i_cut + 1], months_all, sc, bt_nets, ORD[k], b["par_cut"], n_ahead)
    fcs = {"SARIMA-DL": dl_band(paths, sd12, n_ahead)}
    fcs.update(stat_baselines(y[:i_cut + 1], dates[:i_cut + 1], ORD[k], n_ahead))
    truth = y[i_cut + 1:]
    fut_dates = dates[i_cut + 1:]
    bt_paths[k] = dict(dates=fut_dates, truth=truth, fc=fcs, member_paths=paths)
    for m, (mu, sd) in fcs.items():
        err = mu - truth
        ann = pd.Series(err, index=fut_dates).groupby(fut_dates.year).mean()
        row = dict(gas=k[0], site=k[1], method=m, rmse_all=np.sqrt(np.mean(err ** 2)), mae_all=np.mean(np.abs(err)),
                   bias_all=err.mean(),
                   cov80=np.mean(np.abs(err) <= Z80 * sd), cov95=np.mean(np.abs(err) <= Z95 * sd),
                   width95_end=2 * Z95 * sd[-1])
        for yr in [1, 5, 10, 15, 20]:
            if yr <= len(ann):
                row[f"abs_err_y{yr}"] = abs(ann.iloc[yr - 1])
        bt_rows.append(row)
    print("backtest", k, f"{time.time() - t0:.0f}s", flush=True)
BT = pd.DataFrame(bt_rows)
BT.to_csv(RES / "backtest_metrics.csv", index=False)
print(BT.groupby(["gas", "method"])[["rmse_all", "abs_err_y5", "abs_err_y10", "abs_err_y15", "abs_err_y20",
                                      "cov80", "cov95"]].mean().round(3).to_string())

"""### Projections to 2050"""

nets = load_members(RES / "models", prefix="res_")
Pall = pickle.load(open(RES / "pred_all.pkl", "rb"))
pj = {}
for k in KEYS:
    r = C[k]; y = r["y"]; dates = r["dates"]
    n_ahead = (2050 - dates[-1].year) * 12
    T = np.arange(r["i_va"], r["n"] - H)
    e12 = Pall["DL-Residual"][k][:, -1] - y[T + H]          # out-of-sample 12-month errors, 2018-2025
    sd12 = np.sqrt(np.mean(e12 ** 2))
    p, d, q, P, D, Q = ORD[k]
    par_full = SARIMAX(y, order=(p, d, q), seasonal_order=(P, D, Q, 12)).fit(disp=False, maxiter=300).params
    months_all = month_index(dates, n_ahead).month.values
    paths = sarima_dl_paths(y, months_all, r["sc"], nets, ORD[k], par_full, n_ahead)
    fcs = {"SARIMA-DL": dl_band(paths, sd12, n_ahead)}
    fcs.update(stat_baselines(y, dates, ORD[k], n_ahead))
    fut = pd.date_range(dates[-1], periods=n_ahead + 1, freq="MS")[1:]
    pj[k] = dict(dates=fut, fc=fcs, member_paths=paths, sd12=sd12)
    print("projection", k, f"{time.time() - t0:.0f}s", flush=True)

"""### Save projections"""

rows = []
for k, v in pj.items():
    for m, (mu, sd) in v["fc"].items():
        s = pd.DataFrame({"mu": mu, "sd": sd}, index=v["dates"])
        a = s.groupby(s.index.year).agg(mu=("mu", "mean"), sd=("sd", "mean"))
        for yr, rr in a.iterrows():
            rows.append(dict(gas=k[0], site=k[1], method=m, year=yr, mean=rr.mu,
                             lo95=rr.mu - Z95 * rr.sd, hi95=rr.mu + Z95 * rr.sd,
                             lo80=rr.mu - Z80 * rr.sd, hi80=rr.mu + Z80 * rr.sd))
PJ = pd.DataFrame(rows)
PJ.to_csv(RES / "projections_annual.csv", index=False)
print(PJ[(PJ.site == "GLB") & (PJ.year.isin([2030, 2040, 2050]))].round(1).to_string())
with open(RES / "longrange.pkl", "wb") as f:
    pickle.dump(dict(backtest=bt_paths, projection=pj), f)
print("done", f"{time.time() - t0:.0f}s")