"""### Imports and settings"""

import sys, pickle
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))

import numpy as np
import pandas as pd

from ghglib.data import ROOT, GASES, SITES
from ghglib.features import H
from ghglib.evaluate import metrics, dm_test, holm, dm_pooled

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
D = pickle.load(open(RES / "pred_dl.pkl", "rb"))["results"]
B = pickle.load(open(RES / "pred_baselines.pkl", "rb"))["pred"]
KEYS = list(C.keys())
SEEDS = [11, 22, 33, 44, 55]


def mean_of(keys):
    return {k: np.mean([D[m][k] for m in keys], 0) for k in KEYS}


P = {}
P["LSTM-STL"] = mean_of([("causal", "LSTM", s) for s in SEEDS])
P["GRU-STL"] = mean_of([("causal", "GRU", s) for s in SEEDS])
P["CNN-LSTM-STL"] = mean_of([("causal", "CNN-LSTM", s) for s in SEEDS])
P["DL-Ensemble"] = mean_of([("causal", a, s) for a in ["LSTM", "GRU", "CNN-LSTM"] for s in SEEDS])
P["DL-Ensemble (leaky STL)"] = mean_of([("leaky", a, s) for a in ["LSTM", "GRU", "CNN-LSTM"] for s in SEEDS])
P["LSTM-raw"] = mean_of([("raw", "LSTM", s) for s in SEEDS])
seas_c = mean_of([("seas", "LSTM", s) for s in SEEDS]); seas_l = mean_of([("seas_leaky", "LSTM", s) for s in SEEDS])
P["SPL"] = {k: B["SPL-prophet-causal"][k] + seas_c[k] for k in KEYS}
P["SPL (leaky, as published)"] = {k: B["SPL-prophet-leaky"][k] + seas_l[k] for k in KEYS}
for m in ["SNaive-drift", "STL-naive", "SARIMA", "Prophet", "XGBoost-STL", "XGBoost-raw"]:
    P[m] = B[m]
R = pickle.load(open(RES / "pred_residual.pkl", "rb"))
P["DL-Residual"] = {k: np.mean([R[(a, s)][k] for a in ["LSTM", "GRU", "CNN-LSTM"] for s in SEEDS], 0) for k in KEYS}

with open(RES / "pred_all.pkl", "wb") as f:
    pickle.dump(P, f)

"""### Truth and per-horizon metrics"""

TRUTH, LAST = {}, {}
for k in KEYS:
    r = C[k]; T = np.arange(r["i_va"], r["n"] - H)
    TRUTH[k] = np.array([r["y"][t + 1:t + 1 + H] for t in T]); LAST[k] = r["y"][T]

rows = []
for m, pk in P.items():
    for k in KEYS:
        for h in range(1, H + 1):
            mt = metrics(pk[k][:, h - 1], TRUTH[k][:, h - 1], LAST[k])
            rows.append(dict(model=m, gas=k[0], site=k[1], h=h, **mt))
M = pd.DataFrame(rows)
M.to_csv(RES / "metrics_long.csv", index=False)

# skill vs SNaive-drift
ref = M[M.model == "SNaive-drift"].set_index(["gas", "site", "h"])["rmse"]
M["skill"] = 1 - M["rmse"] / M.set_index(["gas", "site", "h"]).index.map(ref).values

"""### Summary per gas: mean over the 5 records, horizons 1, 6, 12 and average 1-12"""

ORDER = ["SNaive-drift", "STL-naive", "SARIMA", "Prophet", "XGBoost-raw", "XGBoost-STL", "LSTM-raw",
         "SPL (leaky, as published)", "SPL", "LSTM-STL", "GRU-STL", "CNN-LSTM-STL", "DL-Ensemble",
         "DL-Ensemble (leaky STL)", "DL-Residual"]
summ = []
for g in GASES:
    for m in ORDER:
        x = M[(M.gas == g) & (M.model == m)]
        row = dict(gas=g, model=m)
        for h in [1, 6, 12]:
            row[f"rmse_h{h}"] = x[x.h == h].rmse.mean()
        row["rmse_avg"] = x.rmse.mean(); row["mae_avg"] = x.mae.mean(); row["mape_avg"] = x.mape.mean()
        row["r2_avg"] = x.r2.mean(); row["r2d_avg"] = x.r2_delta.mean(); row["skill_avg"] = x.skill.mean()
        summ.append(row)
S = pd.DataFrame(summ)
S.to_csv(RES / "summary_by_gas.csv", index=False)
print(S.round(4).to_string())

"""### Diebold-Mariano: reference model vs every other model (15 records x 12 horizons, Holm per comparison)"""

for REF, tag in [("DL-Residual", "main"), ("DL-Ensemble", "dl")]:
    dm_rows = []
    for m in ORDER:
        if m in (REF, "DL-Ensemble (leaky STL)"):
            continue
        stats_, ps = [], []
        for k in KEYS:
            for h in range(1, H + 1):
                e_b = P[m][k][:, h - 1] - TRUTH[k][:, h - 1]
                e_e = P[REF][k][:, h - 1] - TRUTH[k][:, h - 1]
                st, p, dbar = dm_test(e_b, e_e, h)
                stats_.append((k, h, st, dbar)); ps.append(p)
        padj = holm(ps)
        for (k, h, st, dbar), p, pa in zip(stats_, ps, padj):
            dm_rows.append(dict(baseline=m, gas=k[0], site=k[1], h=h, dm=st, p=p, p_holm=pa, dbar=dbar,
                                ens_better=(dbar > 0) and (pa < 0.05), ens_worse=(dbar < 0) and (pa < 0.05),
                                ens_better_raw=(dbar > 0) and (p < 0.05), ens_worse_raw=(dbar < 0) and (p < 0.05)))
    DM = pd.DataFrame(dm_rows)
    DM.to_csv(RES / f"dm_tests_{tag}.csv", index=False)
    dm_sum = DM.groupby("baseline").agg(n=("p", "size"), better=("ens_better", "sum"), worse=("ens_worse", "sum"),
                                        better_raw=("ens_better_raw", "sum"), worse_raw=("ens_worse_raw", "sum"),
                                        median_p=("p_holm", "median"))
    dm_sum = dm_sum.reindex([o for o in ORDER if o in DM.baseline.unique()])
    dm_sum.to_csv(RES / f"dm_summary_{tag}.csv")
    print("REFERENCE:", REF); print(dm_sum.to_string())
    dm_gas = DM.groupby(["baseline", "gas"]).agg(better=("ens_better", "sum"), worse=("ens_worse", "sum"),
                                                 better_raw=("ens_better_raw", "sum"), worse_raw=("ens_worse_raw", "sum"),
                                                 n=("p", "size"))
    dm_gas.to_csv(RES / f"dm_by_gas_{tag}.csv")

"""### Pooled DM per gas and horizon (cross-record mean loss differential), Holm over 36 tests per baseline"""

pool = []
for m in ORDER:
    if m in ("DL-Residual", "DL-Ensemble (leaky STL)"):
        continue
    tmp = []
    for g in GASES:
        ks = [k for k in KEYS if k[0] == g]
        for h in range(1, H + 1):
            eb = [P[m][k][:, h - 1] - TRUTH[k][:, h - 1] for k in ks]
            er = [P["DL-Residual"][k][:, h - 1] - TRUTH[k][:, h - 1] for k in ks]
            st, p, gain = dm_pooled(eb, er, h)
            tmp.append(dict(baseline=m, gas=g, h=h, dm=st, p=p, gain_pct=gain))
    padj = holm([x["p"] for x in tmp])
    for x, pa in zip(tmp, padj):
        x["p_holm"] = pa; x["better"] = (x["gain_pct"] > 0) and (pa < 0.05); x["worse"] = (x["gain_pct"] < 0) and (pa < 0.05)
        pool.append(x)
PO = pd.DataFrame(pool)
PO.to_csv(RES / "dm_pooled_main.csv", index=False)
print(PO.groupby(["baseline", "gas"]).agg(better=("better", "sum"), worse=("worse", "sum"),
                                          mean_gain=("gain_pct", "mean")).round(1).to_string())

"""### Leakage inflation (same networks, leaky vs causal STL inputs)"""

lk = []
for g in GASES:
    for h in range(1, H + 1):
        c = M[(M.gas == g) & (M.h == h) & (M.model == "DL-Ensemble")].rmse.mean()
        l = M[(M.gas == g) & (M.h == h) & (M.model == "DL-Ensemble (leaky STL)")].rmse.mean()
        sc = M[(M.gas == g) & (M.h == h) & (M.model == "SPL")].rmse.mean()
        sl = M[(M.gas == g) & (M.h == h) & (M.model == "SPL (leaky, as published)")].rmse.mean()
        lk.append(dict(gas=g, h=h, ens_causal=c, ens_leaky=l, spl_causal=sc, spl_leaky=sl,
                       ens_inflation_pct=100 * (c - l) / c, spl_inflation_pct=100 * (sc - sl) / sc))
LK = pd.DataFrame(lk)
LK.to_csv(RES / "leakage_inflation.csv", index=False)
print(LK.groupby("gas")[["ens_inflation_pct", "spl_inflation_pct"]].mean().round(1))