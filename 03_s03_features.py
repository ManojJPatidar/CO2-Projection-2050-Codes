"""### Imports and settings"""

import sys, pickle, time
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))

import numpy as np
import pandas as pd

from ghglib.data import ROOT, GASES, SITES, split_dates
from ghglib.features import SeriesFeatures, L, H

RES = ROOT / "results"
sp = split_dates()
panel = pd.read_csv(RES / "panel_monthly.csv", parse_dates=["date"])

"""### Causal and leaky STL features at every origin"""

cache = {}
t0 = time.time()
for g in GASES:
    for s in SITES:
        y = panel[(panel.gas == g) & (panel.site == s)].set_index("date")["value"]
        F = SeriesFeatures(y, sp["train_end"])
        n = F.n
        idx = y.index
        i_tr = int(np.where(idx == sp["train_end"])[0][0])
        i_va = int(np.where(idx == sp["val_end"])[0][0])
        origins = np.arange(F.first_origin(), n)
        rec = dict(Xc=[], Bc=[], Zc=[], Xl=[], Bl=[], Zl=[], Xr=[], Yr=[], Sw=[], Swl=[], S12=[], S12l=[])
        test_comps = {}
        for t in origins:
            xc, d, sc = F.x_causal(t)
            bc = F.base(d, sc, t)
            xl, dl, sl = F.x_leaky(t)
            bl = F.base(dl, sl, t)
            full = t + H <= n - 1
            rec["Xc"].append(xc); rec["Bc"].append(bc)
            rec["Zc"].append(F.target(t, bc) if full else np.full(H, np.nan))
            rec["Xl"].append(xl); rec["Bl"].append(bl)
            rec["Zl"].append(F.target(t, bl) if full else np.full(H, np.nan))
            rec["Xr"].append(F.x_raw(t)); rec["Yr"].append(F.y_raw(t) if full else np.full(H, np.nan))
            rec["Sw"].append(sc[t - L + 1:t + 1] / F.sc_s); rec["S12"].append(sc[t - 11:t + 1])
            rec["Swl"].append(sl[t - L + 1:t + 1] / F.sc_s); rec["S12l"].append(sl[t - 11:t + 1])
            if t >= i_va:                       # keep full causal components at test origins (SPL, Prophet)
                test_comps[t] = (d.copy(), sc.copy())
        rec = {k: np.array(v) for k, v in rec.items()}
        rec.update(origins=origins, i_tr=i_tr, i_va=i_va, n=n, dates=idx, y=F.y,
                   sc=dict(d=F.sc_d, s=F.sc_s, r=F.sc_r, z=F.sc_z, ymin=F.ymin, ymax=F.ymax),
                   leaky_comps=F._leaky, test_comps=test_comps)
        cache[(g, s)] = rec
        print(g, s, len(origins), f"{time.time() - t0:.0f}s", flush=True)

"""### Save feature cache"""

with open(RES / "cache_features.pkl", "wb") as f:
    pickle.dump(cache, f)
print("saved")