os.environ.setdefault("GHG_TORCH_THREADS", "2")

import numpy as np
import pandas as pd

from ghglib.data import ROOT
from ghglib.features import H
from ghglib.dl import train_member, predict

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
SP = pickle.load(open(RES / "sarima_paths.pkl", "rb"))
KEYS = list(C.keys())

"""### Helper functions"""

def pos(r, part):
    o = r["origins"]
    if part == "train":
        m = o + H <= r["i_tr"]
    elif part == "val":
        m = (o >= r["i_tr"]) & (o + H <= r["i_va"])
    else:
        m = (o >= r["i_va"]) & (o + H <= r["n"] - 1)
    return np.where(m)[0]


def base(k, variant, p):
    r = C[k]
    if variant == "V0":
        return r["Bc"][p]
    if variant == "V1":
        # drift from the input window: last 12 monthly growth values (channel 0, scaled)
        g = r["Xc"][p][:, -12:, 0].mean(1) * r["sc"]["d"]
        return r["Bc"][p] + g[:, None] * np.arange(1, H + 1)[None, :]
    if variant == "V3":
        return SP[k]["fc"][p]


def data(variant, part):
    X, Y = [], []
    for k in KEYS:
        r = C[k]; p = pos(r, part); b = base(k, variant, p)
        y = np.array([r["y"][t + 1:t + 1 + H] for t in r["origins"][p]])
        X.append(r["Xc"][p]); Y.append((y - b) / r["sc"]["z"])
    return np.concatenate(X).astype(np.float32), np.concatenate(Y).astype(np.float32)


def val_rmse(nets, variant):
    out = {}
    for k in KEYS:
        r = C[k]; p = pos(r, "val"); b = base(k, variant, p)
        z = np.mean([predict(n, r["Xc"][p]) for n in nets], 0)
        y = np.array([r["y"][t + 1:t + 1 + H] for t in r["origins"][p]])
        out[k] = np.sqrt(np.mean((b + z * r["sc"]["z"] - y) ** 2))
    return out

"""### Train-or-load switch"""

TRAIN_MODELS = False   # False: load the trained weights saved in results/models; True: retrain from scratch (CPU)
import torch
from ghglib.dl import ARCH


def load_net(arch, fname, n_in, n_out=H):
    net = ARCH[arch](n_in, n_out)
    net.load_state_dict(torch.load(RES / "models" / fname, map_location="cpu"))
    net.eval()
    return net

"""### Train or load validation networks"""

rows = []
t0 = time.time()
preds = {}
for v in ["V0", "V1", "V3"]:
    Xtr, Ytr = data(v, "train"); Xva, Yva = data(v, "val")
    nets = []
    for a in ["LSTM", "GRU", "CNN-LSTM"]:
        if TRAIN_MODELS:
            net, ep, vl = train_member(a, Xtr, Ytr, Xva, Yva, 11, refit=False)
            torch.save(net.state_dict(), RES / "models" / f"val{v}_{a}_11.pt")
            print(v, a, ep, round(vl, 4), f"{time.time() - t0:.0f}s", flush=True)
        else:
            net = load_net(a, f"val{v}_{a}_11.pt", Xtr.shape[2])
        nets.append(net)
    preds[v] = {}
    for k in KEYS:
        r = C[k]; p = pos(r, "val")
        preds[v][k] = base(k, v, p) + np.mean([predict(n, r["Xc"][p]) for n in nets], 0) * r["sc"]["z"]

"""### Validation scores"""

for k in KEYS:
    r = C[k]; p = pos(r, "val")
    y = np.array([r["y"][t + 1:t + 1 + H] for t in r["origins"][p]]); s = SP[k]["fc"][p]
    cand = {"SARIMA": s, "V0 (STL-naive base)": preds["V0"][k], "V1 (STL drift base)": preds["V1"][k],
            "V3 (SARIMA base)": preds["V3"][k], "mean(SARIMA, V0)": (s + preds["V0"][k]) / 2,
            "mean(SARIMA, V0, V3)": (s + preds["V0"][k] + preds["V3"][k]) / 3}
    for n_, f_ in cand.items():
        rows.append(dict(variant=n_, gas=k[0], site=k[1], rmse=np.sqrt(np.mean((f_ - y) ** 2))))
V = pd.DataFrame(rows)
V.to_csv(RES / "variant_selection_val.csv", index=False)
print(V.groupby(["variant", "gas"]).rmse.mean().unstack().round(4))