"""### Imports and settings"""

import sys, pickle, time, os
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))
os.environ.setdefault("GHG_TORCH_THREADS", "1")

import numpy as np

from ghglib.data import ROOT
from ghglib.features import H, L
from ghglib.dl import train_member, predict

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
KEYS = list(C.keys())
SEEDS = [11, 22, 33, 44, 55]
ARCHS = ["LSTM", "GRU", "CNN-LSTM"]

"""### Helper functions"""

def split_pos(rec, part):
    o = rec["origins"]; n = rec["n"]
    if part == "train":
        m = o + H <= rec["i_tr"]
    elif part == "val":
        m = (o >= rec["i_tr"]) & (o + H <= rec["i_va"])
    else:
        m = (o >= rec["i_va"]) & (o + H <= n - 1)
    return np.where(m)[0]


def assemble(part, X, Y):
    xs, ys = [], []
    for k in KEYS:
        r = C[k]; p = split_pos(r, part)
        xs.append(r[X][p]); ys.append(r[Y][p])
    return np.concatenate(xs).astype(np.float32), np.concatenate(ys).astype(np.float32)


def seasonal_xy(part, leaky=False):
    """SPL seasonal LSTM: input = scaled seasonal window + month; target = next-12 seasonal values
    (taken from the STL fit 12 months later in the causal case, from the full STL if leaky)."""
    xs, ys = [], []
    for k in KEYS:
        r = C[k]; p = split_pos(r, part)
        sw = r["Swl" if leaky else "Sw"][p]
        Xm = r["Xc"][p][:, :, 3:5]                      # month sin/cos
        x = np.concatenate([sw[:, :, None], Xm], 2)
        if leaky:
            s_full = r["leaky_comps"][1]
            y = np.array([s_full[r["origins"][q] + 1:r["origins"][q] + 1 + H] for q in p]) / r["sc"]["s"]
        else:
            y = np.array([r["S12"][q + H] for q in p]) / r["sc"]["s"]   # S12 at origin t+12 = s(t+1..t+12)
        xs.append(x); ys.append(y)
    return np.concatenate(xs).astype(np.float32), np.concatenate(ys).astype(np.float32)


def to_ppm(kind, preds_scaled):
    """Convert pooled test predictions back to concentration units, per series."""
    out, i = {}, 0
    for k in KEYS:
        r = C[k]; p = split_pos(r, "test"); n = len(p)
        z = preds_scaled[i:i + n]; i += n
        if kind == "causal":
            out[k] = r["Bc"][p] + z * r["sc"]["z"]
        elif kind == "leaky":
            out[k] = r["Bl"][p] + z * r["sc"]["z"]
        elif kind == "raw":
            out[k] = z * (r["sc"]["ymax"] - r["sc"]["ymin"]) + r["sc"]["ymin"]
        elif kind in ("seas", "seas_leaky"):
            out[k] = z * r["sc"]["s"]
    return out

"""### Train-or-load switch"""

TRAIN_MODELS = False   # False: load the trained weights saved in results/models; True: retrain from scratch (CPU)
import torch
from ghglib.dl import ARCH


def load_net(arch, fname, n_in, n_out=H):
    net = ARCH[arch](n_in, n_out)
    net.load_state_dict(torch.load(RES / "models" / fname, map_location="cpu"))
    net.eval()
    return net

"""### Train or load members"""

def wname(kind, a, sd):
    return f"{a}_{sd}.pt" if kind == "causal" else f"{kind}_{a}_{sd}.pt"


results, log = {}, []
t0 = time.time()
for kind, X, Y in [("causal", "Xc", "Zc"), ("leaky", "Xl", "Zl"), ("raw", "Xr", "Yr")]:
    Xtr, Ytr = assemble("train", X, Y); Xva, Yva = assemble("val", X, Y); Xte, _ = assemble("test", X, Y)
    archs = ARCHS if kind != "raw" else ["LSTM"]
    for a in archs:
        for sd in SEEDS:
            if TRAIN_MODELS:
                net, ep, vl = train_member(a, Xtr, Ytr, Xva, Yva, sd)
                log.append(dict(kind=kind, arch=a, seed=sd, best_epoch=ep, val_mse=vl))
                os.makedirs(RES / "models", exist_ok=True)
                torch.save(net.state_dict(), RES / "models" / wname(kind, a, sd))
                print(kind, a, sd, ep, round(vl, 4), f"{time.time() - t0:.0f}s", flush=True)
            else:
                net = load_net(a, wname(kind, a, sd), Xte.shape[2])
            results[(kind, a, sd)] = to_ppm(kind, predict(net, Xte))

for kind, leaky in [("seas", False), ("seas_leaky", True)]:
    Xtr, Ytr = seasonal_xy("train", leaky); Xva, Yva = seasonal_xy("val", leaky); Xte, _ = seasonal_xy("test", leaky)
    for sd in SEEDS:
        if TRAIN_MODELS:
            net, ep, vl = train_member("LSTM", Xtr, Ytr, Xva, Yva, sd)
            log.append(dict(kind=kind, arch="LSTM", seed=sd, best_epoch=ep, val_mse=vl))
            torch.save(net.state_dict(), RES / "models" / f"{kind}_LSTM_{sd}.pt")
            print(kind, sd, ep, round(vl, 4), f"{time.time() - t0:.0f}s", flush=True)
        else:
            net = load_net("LSTM", f"{kind}_LSTM_{sd}.pt", Xte.shape[2])
        results[(kind, "LSTM", sd)] = to_ppm(kind, predict(net, Xte))
print(len(results), "members", f"{time.time() - t0:.0f}s")

"""### Save predictions and training log"""

with open(RES / "pred_dl.pkl", "wb") as f:
    pickle.dump(dict(results=results, keys=KEYS), f)
import pandas as pd
if TRAIN_MODELS:
    pd.DataFrame(log).to_csv(RES / "dl_training_log.csv", index=False)
print(pd.read_csv(RES / "dl_training_log.csv").groupby(["kind", "arch"])[["best_epoch", "val_mse"]].mean().round(4))
print("done", f"{time.time() - t0:.0f}s")