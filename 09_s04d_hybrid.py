"""### Imports and settings"""

import sys, pickle, os, time
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))
os.environ.setdefault("GHG_TORCH_THREADS", "2")

import numpy as np
import torch

from ghglib.data import ROOT
from ghglib.features import H
from ghglib.dl import train_member, predict

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
SP = pickle.load(open(RES / "sarima_paths.pkl", "rb"))
KEYS = list(C.keys())
SEEDS = [11, 22, 33, 44, 55]

"""### Helper functions"""

def pos(r, part):
    o = r["origins"]
    if part == "train":
        m = o + H <= r["i_tr"]
    elif part == "val":
        m = (o >= r["i_tr"]) & (o + H <= r["i_va"])
    else:
        m = (o >= r["i_va"]) & (o + H <= r["n"] - 1)
    return np.where(m)[0]


def data(part):
    X, Y = [], []
    for k in KEYS:
        r = C[k]; p = pos(r, part)
        y = np.array([r["y"][t + 1:t + 1 + H] for t in r["origins"][p]])
        X.append(r["Xc"][p]); Y.append((y - SP[k]["fc"][p]) / r["sc"]["z"])
    return np.concatenate(X).astype(np.float32), np.concatenate(Y).astype(np.float32)

"""### Train-or-load switch"""

TRAIN_MODELS = False   # False: load the trained weights saved in results/models; True: retrain from scratch (CPU)
import torch
from ghglib.dl import ARCH


def load_net(arch, fname, n_in, n_out=H):
    net = ARCH[arch](n_in, n_out)
    net.load_state_dict(torch.load(RES / "models" / fname, map_location="cpu"))
    net.eval()
    return net

"""### Train or load SARIMA-DL members"""

Xtr, Ytr = data("train"); Xva, Yva = data("val")
res = {}
t0 = time.time()
os.makedirs(RES / "models", exist_ok=True)
for a in ["LSTM", "GRU", "CNN-LSTM"]:
    for sd in SEEDS:
        if TRAIN_MODELS:
            net, ep, vl = train_member(a, Xtr, Ytr, Xva, Yva, sd)
            torch.save(net.state_dict(), RES / "models" / f"res_{a}_{sd}.pt")
            print(a, sd, ep, round(vl, 4), flush=True)
        else:
            net = load_net(a, f"res_{a}_{sd}.pt", Xtr.shape[2])
        res[(a, sd)] = {}
        for k in KEYS:
            r = C[k]; p = pos(r, "test")
            res[(a, sd)][k] = SP[k]["fc"][p] + predict(net, r["Xc"][p]) * r["sc"]["z"]
        print(a, sd, f"{time.time() - t0:.0f}s", flush=True)

"""### Save predictions"""

with open(RES / "pred_residual.pkl", "wb") as f:
    pickle.dump(res, f)
print("done")