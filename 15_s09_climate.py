"""### Imports and settings"""

import sys, pickle
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))

import numpy as np
import pandas as pd
import statsmodels.api as sm
from statsmodels.tsa.stattools import coint, adfuller

from ghglib.data import ROOT, load_gistemp, load_oni, load_sf6_global, GASES
from ghglib.climate import forcing, SSP_2050

RES = ROOT / "results"
panel = pd.read_csv(RES / "panel_monthly.csv", parse_dates=["date"])


def annual(g, s, col="value"):
    x = panel[(panel.gas == g) & (panel.site == s)].set_index("date")[col]
    a = x.groupby(x.index.year).agg(["mean", "count"])
    return a[a["count"] == 12]["mean"]

"""### Annual global means; N2O before 2001 from the 4-station mean, offset-matched to GLB (2001-2005)"""

co2 = annual("co2", "GLB"); ch4 = annual("ch4", "GLB"); n2o_g = annual("n2o", "GLB")
st = pd.concat([annual("n2o", s) for s in ["BRW", "MLO", "SMO", "SPO"]], axis=1).mean(1)
off = (n2o_g.loc[2001:2005] - st.loc[2001:2005]).mean()
n2o = pd.concat([st.loc[:2000] + off, n2o_g]).sort_index()
# 1984-1997: linear back-extension of the 1998-2010 N2O trend (N2O growth is close to linear)
fit = np.polyfit(n2o.loc[1998:2010].index, n2o.loc[1998:2010].values, 1)
back = pd.Series(np.polyval(fit, np.arange(1984, 1998)), index=np.arange(1984, 1998))
n2o_ext = pd.concat([back, n2o]).sort_index()
sf6 = load_sf6_global(); sf6a = sf6.groupby(sf6.index.year).mean()
yrs = np.arange(1984, 2026)
G = pd.DataFrame({"co2": co2.reindex(yrs), "ch4": ch4.reindex(yrs), "n2o": n2o_ext.reindex(yrs),
                  "sf6": sf6a.reindex(yrs)})
F = pd.DataFrame(forcing(G.co2.values, G.ch4.values, G.n2o.values, G.sf6.fillna(0).values), index=yrs)
F.loc[F.index < 1998, "sf6"] = np.nan
F["total"] = F[["co2", "ch4", "n2o"]].sum(1) + F["sf6"].fillna(0)
F.to_csv(RES / "forcing_annual.csv")

shares = []
for y in [1984, 2005, 2025]:
    row = F.loc[y]
    shares.append(dict(year=y, **{g: row[g] for g in ["co2", "ch4", "n2o", "sf6"]}, total=row.total,
                       **{f"share_{g}": 100 * row[g] / row.total for g in ["co2", "ch4", "n2o", "sf6"]}))
dF = F.loc[2025] - F.loc[2005]
shares.append(dict(year="increase 2005-2025", **{g: dF[g] for g in ["co2", "ch4", "n2o", "sf6"]}, total=dF.total,
                   **{f"share_{g}": 100 * dF[g] / dF.total for g in ["co2", "ch4", "n2o", "sf6"]}))
SH = pd.DataFrame(shares)
SH.to_csv(RES / "forcing_shares.csv", index=False)
print(SH.round(3).to_string())

"""### Temperature regression (annual, 1984-2025)"""

Tm, Ta = load_gistemp(); oni = load_oni()
base_pi = Ta.loc[1880:1900].mean()                 # 1880-1900 mean, used as pre-industrial proxy
T = (Ta - base_pi).reindex(yrs)
oni_a = oni.groupby(oni.index.year).mean().reindex(yrs)
pin = pd.Series(0.0, index=yrs); pin.loc[[1992, 1993]] = 1.0     # Pinatubo cooling years
X = sm.add_constant(pd.DataFrame({"F": F.total, "ONI": oni_a, "Pinatubo": pin}))
ols = sm.OLS(T, X).fit(cov_type="HAC", cov_kwds={"maxlags": 2})
print(ols.summary())
X2 = sm.add_constant(pd.DataFrame({"F_co2": F.co2, "F_other": F.total - F.co2, "ONI": oni_a, "Pinatubo": pin}))
ols2 = sm.OLS(T, X2).fit(cov_type="HAC", cov_kwds={"maxlags": 2})
eg_stat, eg_p, _ = coint(T.values, F.total.values)
adf_T = adfuller(T.values, autolag="AIC")[1]; adf_F = adfuller(F.total.values, autolag="AIC")[1]
corr = {g: np.corrcoef(T.values, F[g].values)[0, 1] for g in ["co2", "ch4", "n2o", "total"]}
reg = dict(beta=ols.params.F, beta_se=ols.bse.F, beta_lo=ols.conf_int().loc["F", 0], beta_hi=ols.conf_int().loc["F", 1],
           alpha=ols.params.const, gamma_oni=ols.params.ONI, gamma_oni_p=ols.pvalues.ONI,
           pin=ols.params.Pinatubo, pin_p=ols.pvalues.Pinatubo, r2=ols.rsquared, n=int(ols.nobs),
           beta_co2=ols2.params.F_co2, beta_other=ols2.params.F_other,
           eg_stat=eg_stat, eg_p=eg_p, adf_T=adf_T, adf_F=adf_F, base_pi=base_pi,
           **{f"corr_{g}": v for g, v in corr.items()})
pd.Series(reg).to_csv(RES / "temperature_regression.csv")
print(pd.Series(reg).round(4))

"""### Implied warming from the projected concentrations (ENSO-neutral, no volcano)"""

PJ = pd.read_csv(RES / "projections_annual.csv")
rng = np.random.default_rng(42)
nsim = 5000
beta_draw = rng.normal(ols.params.F, ols.bse.F, nsim)
alpha_draw = ols.params.const + (beta_draw - ols.params.F) * (-X.F.mean())   # keep the fit centred on mean F
out, cross = [], []
Fpaths = {}
for m in ["SARIMA-DL", "SARIMA", "Prophet", "Quadratic trend"]:
    q = PJ[(PJ.site == "GLB") & (PJ.method == m)].pivot(index="year", columns="gas", values="mean")
    sdq = PJ[(PJ.site == "GLB") & (PJ.method == m)].assign(sd=lambda d: (d.hi95 - d.lo95) / (2 * 1.959964)) \
        .pivot(index="year", columns="gas", values="sd")
    s6 = pd.Series(sf6a.loc[2025] + (sf6a.loc[2025] - sf6a.loc[2015]) / 10 * (q.index.values - 2025), index=q.index)  # SF6 linear extension
    Fq = pd.DataFrame(forcing(q.co2.values, q.ch4.values, q.n2o.values, s6.values), index=q.index)
    Fq["total"] = Fq.sum(1)
    Fpaths[m] = Fq
    # Monte Carlo over concentration uncertainty (2050) and beta
    c = rng.normal(q.loc[2050, "co2"], sdq.loc[2050, "co2"], nsim)
    mm = rng.normal(q.loc[2050, "ch4"], sdq.loc[2050, "ch4"], nsim)
    nn = rng.normal(q.loc[2050, "n2o"], sdq.loc[2050, "n2o"], nsim)
    Ft = sum(forcing(c, mm, nn, np.full(nsim, s6.loc[2050])).values())
    Tsim = alpha_draw + beta_draw * Ft
    Tc = ols.params.const + ols.params.F * Fq["total"]
    yr15 = Tc[Tc >= 1.5].index.min() if (Tc >= 1.5).any() else np.nan
    out.append(dict(method=m, co2_2050=q.loc[2050, "co2"], ch4_2050=q.loc[2050, "ch4"], n2o_2050=q.loc[2050, "n2o"],
                    F_2050=Fq.loc[2050, "total"], F_co2_2050=Fq.loc[2050, "co2"],
                    share_co2_2050=100 * Fq.loc[2050, "co2"] / Fq.loc[2050, "total"],
                    T_2050=float(np.median(Tsim)), T_2050_lo=float(np.percentile(Tsim, 2.5)),
                    T_2050_hi=float(np.percentile(Tsim, 97.5)), year_cross_1p5=yr15))
for name, v in SSP_2050.items():
    Fs = forcing(v["co2"], v["ch4"], v["n2o"], s6.loc[2050])
    Ft = sum(Fs.values())
    out.append(dict(method=name, co2_2050=v["co2"], ch4_2050=v["ch4"], n2o_2050=v["n2o"], F_2050=Ft,
                    F_co2_2050=Fs["co2"], share_co2_2050=100 * Fs["co2"] / Ft,
                    T_2050=ols.params.const + ols.params.F * Ft))
W = pd.DataFrame(out)
W.to_csv(RES / "warming_2050.csv", index=False)
print(W.round(3).to_string())
T_fit = ols.params.const + ols.params.F * F.total
pd.DataFrame({"T_obs": T, "T_fit_enso_neutral": T_fit, "F_total": F.total, "ONI": oni_a}).to_csv(RES / "temperature_annual.csv")
with open(RES / "forcing_paths.pkl", "wb") as f:
    pickle.dump(Fpaths, f)

"""### North-south gradient: BRW - SPO annual means"""

ns = []
for g in GASES:
    a = annual(g, "BRW") - annual(g, "SPO")
    a = a.dropna()
    x = sm.add_constant(a.index.values - a.index.values[0])
    fitg = sm.OLS(a.values, x).fit(cov_type="HAC", cov_kwds={"maxlags": 2})
    glb_growth = annual(g, "GLB").diff()
    cc = pd.concat([a, glb_growth], axis=1).dropna()
    ns.append(dict(gas=g, start=int(a.index[0]), end=int(a.index[-1]), first5=a.iloc[:5].mean(), last5=a.iloc[-5:].mean(),
                   slope_per_decade=10 * fitg.params[1], slope_lo=10 * fitg.conf_int()[1, 0],
                   slope_hi=10 * fitg.conf_int()[1, 1], slope_p=fitg.pvalues[1],
                   corr_with_global_growth=np.corrcoef(cc.iloc[:, 0], cc.iloc[:, 1])[0, 1]))
    a.to_csv(RES / f"ns_gradient_{g}.csv")
NS = pd.DataFrame(ns)
NS.to_csv(RES / "ns_gradient_summary.csv", index=False)
print(NS.round(3).to_string())