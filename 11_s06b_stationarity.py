import numpy as np
import pandas as pd
from statsmodels.tsa.stattools import adfuller, kpss

from ghglib.data import ROOT, GASES, SITES, split_dates

RES = ROOT / "results"
sp = split_dates()
panel = pd.read_csv(RES / "panel_monthly.csv", parse_dates=["date"])

"""### ADF and KPSS tests"""

rows = []
for g in GASES:
    for s in SITES:
        y = panel[(panel.gas == g) & (panel.site == s)].set_index("date")["value"]
        y = y[y.index <= sp["train_end"]]
        d1 = y.diff().dropna(); d12 = y.diff().diff(12).dropna()
        row = dict(gas=g, site=s)
        for name, x in [("level", y), ("diff1", d1), ("diff1_12", d12)]:
            row[f"adf_p_{name}"] = adfuller(x.values, autolag="AIC", regression="ct" if name == "level" else "c")[1]
            row[f"kpss_p_{name}"] = kpss(x.values, regression="ct" if name == "level" else "c", nlags="auto")[1]
        rows.append(row)
ST = pd.DataFrame(rows)
ST.to_csv(RES / "stationarity.csv", index=False)
print(ST.round(3).to_string())