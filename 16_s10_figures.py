"""### Fig05_dm"""

DM = pd.read_csv(RES / "dm_tests_main.csv")
bl = ["SNaive-drift", "STL-naive", "SARIMA", "Prophet", "XGBoost-raw", "XGBoost-STL", "LSTM-raw",
      "SPL (leaky, as published)", "SPL", "LSTM-STL", "GRU-STL", "CNN-LSTM-STL", "DL-Ensemble"]
bl = [b for b in bl if b in DM.baseline.unique()]
score = np.zeros((len(bl), 12))
for i, b in enumerate(bl):
    for h in range(1, 13):
        d = DM[(DM.baseline == b) & (DM.h == h)]
        score[i, h - 1] = d.ens_better.sum() - d.ens_worse.sum()
fig, ax = plt.subplots(figsize=(FULL, 2.9))
cmap = mcolors.LinearSegmentedColormap.from_list("bw", ["#0000FF", "#FFFFFF", "#FF0000"])
im = ax.imshow(score, cmap=cmap, vmin=-15, vmax=15, aspect="auto")
for i in range(len(bl)):
    for h in range(12):
        ax.text(h, i, f"{int(score[i, h]):d}", ha="center", va="center", fontsize=7)
ax.set_yticks(range(len(bl))); ax.set_yticklabels([lab(b) for b in bl], fontsize=7.5)
ax.set_xticks(range(12)); ax.set_xticklabels(range(1, 13)); ax.set_xlabel("Horizon (months)")
ax.grid(False)
cb = fig.colorbar(im, ax=ax, fraction=0.03, pad=0.02)
cb.set_label("records: SARIMA-DL significantly better\nminus significantly worse (of 15)", fontsize=7)
plt.show()
save(fig, "fig05_dm")

"""### Fig06_longrange"""

import matplotlib.dates as mdates
LR = pickle.load(open(RES / "longrange.pkl", "rb"))
PJ = pd.read_csv(RES / "projections_annual.csv")
panel = pd.read_csv(RES / "panel_monthly.csv", parse_dates=["date"])
Z95 = 1.959964
lcol = {"SARIMA-DL": "#FF0000", "SARIMA": "#000000", "Prophet": "#FF8C00", "Quadratic trend": "#008000"}
lmk = {"SARIMA-DL": "o", "SARIMA": "v", "Prophet": "P", "Quadratic trend": "s"}
sspc = {"SSP1-1.9": "#00BFFF", "SSP1-2.6": "#008000", "SSP2-4.5": "#FF8C00", "SSP3-7.0": "#FF0000",
        "SSP5-8.5": "#8B0000"}
fig, axs = plt.subplots(2, 3, figsize=(FULL, 5.2))
for j, g in enumerate(GASES):
    ax = axs[0, j]
    b = LR["backtest"][(g, "GLB")]
    dts = b["dates"]
    ax.plot(dts, b["truth"], color="#808080", lw=1.0, label="Observed")
    for m, (mu, sd) in b["fc"].items():
        ax.plot(dts, mu, color=lcol[m], lw=1.6 if m == "SARIMA-DL" else 1.0, marker=lmk[m], markevery=24, ms=3.2,
                label=m + (" ensemble" if m == "SARIMA-DL" else ""))
        if m == "SARIMA-DL":
            ax.fill_between(dts, mu - Z95 * sd, mu + Z95 * sd, color="#FF0000", alpha=0.15, lw=0, label="SARIMA-DL 95% band")
    ax.xaxis.set_major_locator(mdates.YearLocator(10 if g != "n2o" else 5, month=1)); ax.xaxis.set_minor_locator(mdates.YearLocator(5))
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
    ax.set_title(f"({TAG[j]}) {LABEL[g]}: backtest", loc="left"); ax.set_ylabel(f"{LABEL[g]} ({UNITS[g]})")
    ax = axs[1, j]
    obs = panel[(panel.gas == g) & (panel.site == "GLB")].set_index("date").value
    oa = obs.groupby(obs.index.year).mean()
    ax.plot(oa.index, oa.values, color="#808080", lw=1.4)
    for m in ["SARIMA-DL", "SARIMA", "Prophet", "Quadratic trend"]:
        d = PJ[(PJ.gas == g) & (PJ.site == "GLB") & (PJ.method == m)]
        ax.plot(d.year, d["mean"], color=lcol[m], marker=lmk[m], markevery=5, ms=3.2, lw=1.6 if m == "SARIMA-DL" else 1.0)
        if m == "SARIMA-DL":
            ax.fill_between(d.year, d.lo95, d.hi95, color="#FF0000", alpha=0.15, lw=0)
    for k, v in SSP_2050.items():
        ax.plot(2050.8, v[g], marker="<", color=sspc[k], ms=6, ls="none", label=k)
    ax.set_xlim(1995, 2053)
    ax.set_title(f"({TAG[j + 3]}) {LABEL[g]}: projection", loc="left"); ax.set_ylabel(f"{LABEL[g]} ({UNITS[g]})")
h1, l1 = axs[0, 0].get_legend_handles_labels(); h2, l2 = axs[1, 0].get_legend_handles_labels()
fig.tight_layout(rect=(0, 0.11, 1, 1))
fig.legend(h1 + h2, l1 + l2, loc="lower center", ncol=6, fontsize=6.6, frameon=False)
plt.show()
save(fig, "fig06_longrange")

