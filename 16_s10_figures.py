"""### Fig03_imputation"""

R = pd.read_csv(RES / "imputation_reconstruction.csv")
E = pd.read_csv(RES / "edge_gap_summary.csv")
scen = ["MCAR 5%", "MCAR 10%", "MCAR 20%", "Block 3 m", "Block 6 m", "Block 12 m"]
meths = ["LOCF", "Linear", "Prophet", "STL-seasonal"]
mcol = {"LOCF": "#808080", "Linear": "#0000FF", "Prophet": "#FF8C00", "STL-seasonal": "#FF0000"}
fig, axs = plt.subplots(2, 2, figsize=(FULL, 4.3))
for ax, g in zip(axs.flat[:3], GASES):
    t = R[R.gas == g].groupby(["scenario", "method"]).rmse.mean().unstack()
    x = np.arange(len(scen)); w = 0.2
    for i, m in enumerate(meths):
        ax.bar(x + (i - 1.5) * w, t.loc[scen, m], w, color=mcol[m], edgecolor="k", lw=0.6, label=m)
    ax.set_xticks(x); ax.set_xticklabels(["5%", "10%", "20%", "3 m", "6 m", "12 m"], fontsize=7.5)
    ax.axvline(2.5, color="k", lw=0.8, ls=":")
    ax.text(1.0, 1.02, "random gaps", transform=ax.get_xaxis_transform(), ha="center", fontsize=7)
    ax.text(4.0, 1.02, "block gaps", transform=ax.get_xaxis_transform(), ha="center", fontsize=7)
    ax.set_ylabel(f"RMSE ({UNITS[g]})")
    ax.set_title(f"({TAG[GASES.index(g)]}) {LABEL[g]}", loc="left", pad=12)
axs[0, 0].set_ylim(0, 4.9); axs[0, 0].legend(ncol=2, fontsize=7, loc="upper left")
ax = axs[1, 1]
order = ["Linear (full record)", "Prophet (full record)", "LOCF", "STL-seasonal (causal)", "Prophet (history only)"]
ecol = {"Linear (full record)": "#00BFFF", "Prophet (full record)": "#FFD27F", "LOCF": "#808080",
        "STL-seasonal (causal)": "#FF0000", "Prophet (history only)": "#FF8C00"}
comp = E[E.method == "Complete history"].groupby("gas").fc_rmse.mean()
x = np.arange(3); w = 0.16
for i, m in enumerate(order):
    v = [E[(E.gas == g) & (E.g == 6) & (E.method == m)].fc_rmse.mean() / comp[g] for g in GASES]
    ax.bar(x + (i - 2) * w, v, w, color=ecol[m], edgecolor="k", lw=0.6, hatch="//" if "full" in m else None,
           label=m.replace(" record", "").replace(" only", "").replace(" (causal)", ""))
ax.axhline(1, color="k", ls="--", lw=1)
ax.set_xticks(x); ax.set_xticklabels([LABEL[g] for g in GASES])
ax.set_ylabel("RMSE ratio (gap / no gap)")
ax.set_ylim(0, 10)
ax.set_title("(d) 6-month gap before the origin", loc="left", pad=12)
ax.legend(fontsize=6.8, ncol=2, loc="upper right")
fig.tight_layout()
plt.show()
save(fig, "fig03_imputation")

"""### Fig04_accuracy"""

