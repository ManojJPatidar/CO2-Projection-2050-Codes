import sys, pickle
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent if Path.cwd().name == "scripts" else Path.cwd()))

import numpy as np
import xgboost as xgb

from ghglib.data import ROOT
from ghglib.features import H

RES = ROOT / "results"
C = pickle.load(open(RES / "cache_features.pkl", "rb"))
B = pickle.load(open(RES / "pred_baselines.pkl", "rb"))

"""### Helper functions"""

def split_pos(r, part):
    o = r["origins"]
    if part == "train":
        m = o + H <= r["i_tr"]
    elif part == "val":
        m = (o >= r["i_tr"]) & (o + H <= r["i_va"])
    else:
        m = (o >= r["i_va"]) & (o + H <= r["n"] - 1)
    return np.where(m)[0]


def feats(r, part):
    p = split_pos(r, part); y = r["y"]; o = r["origins"][p]; dates = r["dates"]
    mon = dates[o].month.values; yr = dates[o].year.values + (mon - 1) / 12
    X = np.column_stack([np.array([y[t - 11:t + 1] for t in o]), np.sin(2 * np.pi * mon / 12),
                         np.cos(2 * np.pi * mon / 12), yr])
    return X, np.array([y[t + 1:t + 1 + H] for t in o])

"""### Per-record XGBoost"""

for k, r in C.items():
    Xtr, Ytr = feats(r, "train"); Xva, Yva = feats(r, "val"); Xte, _ = feats(r, "test")
    kw = dict(n_estimators=2000, max_depth=4, learning_rate=0.03, subsample=0.8, colsample_bytree=0.8,
              tree_method="hist", random_state=7, n_jobs=1)
    m = xgb.XGBRegressor(early_stopping_rounds=50, **kw).fit(Xtr, Ytr, eval_set=[(Xva, Yva)], verbose=False)
    kw["n_estimators"] = m.best_iteration + 1
    m2 = xgb.XGBRegressor(**kw).fit(np.concatenate([Xtr, Xva]), np.concatenate([Ytr, Yva]), verbose=False)
    B["pred"]["XGBoost-raw"][k] = m2.predict(Xte)
    print(k, kw["n_estimators"], flush=True)

"""### Save"""

with open(RES / "pred_baselines.pkl", "wb") as f:
    pickle.dump(B, f)
print("done")